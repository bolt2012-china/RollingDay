/* RollingDay PWA service worker — bump CACHE when shell changes */
const CACHE = "rollingday-pwa-v1";
const SHELL = [
  "./",
  "./index.html",
  "./manifest.webmanifest",
  "./icons/icon-192.png",
  "./icons/icon-512.png",
  "./icons/apple-touch-icon.png"
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(SHELL)).then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))
    ).then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  event.respondWith(
    caches.match(req).then((cached) => {
      const network = fetch(req)
        .then((res) => {
          if (res && res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((cache) => cache.put(req, copy));
          }
          return res;
        })
        .catch(() => cached);
      // App shell: prefer cache for instant offline; still update in background
      if (cached && (url.pathname.endsWith("/") || url.pathname.endsWith("index.html") || url.pathname.endsWith(".js") || url.pathname.endsWith(".webmanifest") || url.pathname.endsWith(".png"))) {
        return cached;
      }
      return network.then((res) => res || cached || new Response("离线不可用", { status: 503 }));
    })
  );
});
